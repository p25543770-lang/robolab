# ============================================================================
# Робот качается из стороны в сторону на прямой
#    → уменьши KP, либо увеличь KD.
# Робот «плавает» и не возвращается на линию
#    → увеличь KP.
# На чередовании клеток (шахматке) робот дёргается
#    → уменьши BG_ALPHA (медленнее верим новому цвету клетки)
#      и/или увеличь HYST.
# Робот не вписывается в крутой поворот и сходит с линии
#    → уменьши BASE_POWER и/или увеличь SLOW_DOWN.
# Робот едет зеркально (уходит в обратную сторону от линии)
#    → поменяй местами датчики S1/S2, либо поменяй знак у turn
#      (motor_left.dc(power + turn ...) и motor_right.dc(power - turn ...)).
# Робот не останавливается на финише
#    → увеличь BRIGHT_MARK ближе к WHITE_REF, либо уменьши FINISH_MS.
# Робот остановился посреди трассы «по-белому»
#    → уменьши BRIGHT_MARK или увеличь FINISH_MS
#      (на чёрной клетке с белой линией финиш срабатывать не должен —
#       там фон чёрный и on_white_bg = False).
# ============================================================================
