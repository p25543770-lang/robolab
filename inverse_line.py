# ============================================================================
#  РОБОЛАБ «Большое путешествие» — старшая категория (13–17 лет)
#  Полигон 3. «Следование по инверсной линии»   (прямое C → D, обратное E → F)
#  Регламент, пункт 3.7 и 3.17 (Приложение 5 к Положению)
#
#  Что делает программа:
#    Робот едет вдоль линии от зоны старта до зоны финиша.
#    Поле — «шахматка» из чёрных и белых клеток (старт и финиш — белые).
#    Цвет линии ВСЕГДА противоположен клетке, по которой она идёт:
#      на белой клетке — чёрная линия,  на чёрной клетке — белая линия.
#
#  Как это работает (коротко):
#    1. Два датчика отражённого света снизу (S1 слева, S2 справа) смотрят на линию.
#    2. Программа следит за СРЕДНЕЙ яркостью — по ней понимает, на какой клетке
#       мы едем: белая или чёрная. Это и есть «инверсия».
#    3. Ошибка считается так, чтобы «линия слева» всегда означала «поверни налево»,
#       независимо от цвета клетки.
#    4. Мощность моторам задаётся напрямую через motor.dc(мощность), без ПИД-регулятора
#       оборотов: поворот подмешивается к общей мощности.
#
#  Перед заездом:
#    1) Поставь MODE = 'calib', запусти, проведи робота над белой и чёрной клеткой,
#       запиши WHITE_REF и BLACK_REF ниже.
#    2) Верни MODE = 'run' и заезжай.
#
#  Важно (регламент п. 4.4–4.5): программу должен понимать и уметь объяснить
#  участник. Поэтому весь код разобран по шагам — меняй цифры и смотри,
#  что получается.
# ============================================================================

from pybricks.hubs import EV3Brick
from pybricks.ev3devices import Motor, ColorSensor, UltrasonicSensor
from pybricks.parameters import Port, Direction
from pybricks.tools import wait, StopWatch

brick = EV3Brick()

# ============================================================================
# 1. ПОРТЫ (по конструкции робота)
# ============================================================================
# S1 — датчик отражённого света / яркости, СЛЕВА, смотрит вниз
sensor_left = ColorSensor(Port.S1)
# S2 — датчик отражённого света / яркости, СПРАВА, смотрит вниз
sensor_right = ColorSensor(Port.S2)
# S3 — ультразвук, смотрит ВПЕРЁД (на этом полигоне не используется)
us_front = UltrasonicSensor(Port.S3)
# S4 — датчик, смотрит ВПРАВО (на этом полигоне не используется).
#      Если в S4 стоит инфракрасный датчик, а не ультразвук, замени строку на:
#      from pybricks.ev3devices import InfraredSensor
#      us_right = InfraredSensor(Port.S4)
us_right = UltrasonicSensor(Port.S4)

# B — ПРАВЫЙ мотор, C — ЛЕВЫЙ мотор (стоит зеркально, поэтому COUNTERCLOCKWISE)
motor_right = Motor(Port.B)
motor_left = Motor(Port.C, Direction.COUNTERCLOCKWISE)
# D — подъём сзади (на этом полигоне не используется; задел на «Кегельринг»)
lift_motor = Motor(Port.D)

# ============================================================================
# 2. РЕЖИМ
# ============================================================================
MODE = 'run'        # 'run' — заезд, 'calib' — замер отражения для настройки

# ============================================================================
# 3. НАСТРОЙКИ — МЕНЯЙ ТУТ, больше нигде
# ============================================================================

# --- Отражение (узнай свои значения в режиме 'calib') ---
WHITE_REF = 62      # что показывает датчик на белой клетке / белой зоне
BLACK_REF = 8       # что показывает датчик на чёрной клетке

# --- Скорость и повороты ---
BASE_POWER = 30     # мощность на прямой, dc(-100..100). Больше = быстрее, но хуже держит линию
KP = 0.9            # пропорциональный коэффициент: насколько резко реагируем на уход с линии
KD = 1.5            # дифференциальный коэффициент: гасит раскачку на прямых
MAX_TURN = 50       # предел подмешивания поворота (чтобы робот не развернуло на месте)
SLOW_DOWN = 14      # на сколько снимать мощность в крутых поворотах (0 — не снижать)
ERROR_FULL = 60     # ошибка, при которой поворот считается «полным» (для торможения)

# --- Фон (шахматка) ---
BG_ALPHA = 0.20     # как быстро привыкаем к новому цвету клетки (0.05 медленно … 0.4 быстро)
HYST = 8            # гистерезис: середину около MID проходим «не веря» показаниям (анти-мерцание)

# --- Финиш ---
BRIGHT_MARK = 45    # значение выше этого — «датчик видит белое» (между MID и WHITE_REF)
ON_LINE_ERROR = 15  # такая ошибка (или больше) означает «линия была поймана»
FINISH_MS = 2000    # столько мс ОБА датчика видят белое и мы на белом фоне → финиш
MAX_RUN_MS = 120000  # предохранитель: дальше 2 минут не ехать

LOOP_MS = 10        # пауза в главном цикле

# Производные величины — обычно не трогай
MID = (WHITE_REF + BLACK_REF) / 2.0   # середина между чёрным и белым

# ============================================================================
# 4. МАЛЕНЬКИЕ ФУНКЦИИ (чтобы главный цикл был понятен)
# ============================================================================

def clamp(value, low, high):
    """Зажать число в границы: clamp(150, -100, 100) -> 100."""
    return max(low, min(high, value))


def is_background_white(bg_level, was_white):
    """
    По плавной оценке средней яркости понимаем цвет клетки под роботом.
    Пока не определились (серединка) — держим прошлое состояние.
    """
    if bg_level > MID + HYST:
        return True    # белая клетка (или белая зона старта/финиша)
    if bg_level < MID - HYST:
        return False   # чёрная клетка
    return was_white


def cell_is_white(left, right, bg_level, was_white):
    """
    Точное определение цвета клетки под роботом с учётом обеих показаний.

    - обе тёмные  -> это ЧЁРНАЯ клетка (белого фона там не бывает);
    - обе яркие   -> белая клетка ЛИБО белая линия на чёрной клетке:
                     решаем по медленной оценке фона bg_level;
    - смешанные   -> решаем по bg_level (там, где уверены), иначе было.
    """
    both_dark = (left < MID - HYST) and (right < MID - HYST)
    both_bright = (left > MID + HYST) and (right > MID + HYST)
    if both_dark:
        return False
    if both_bright:
        return bg_level >= MID
    return is_background_white(bg_level, was_white)


def line_error(left, right, on_white_bg):
    """
    Ошибка: > 0 — линия ЛЕВЕЕ робота, < 0 — линия ПРАВЕЕ робота.
    Знак одинаковый для любой клетки, поэтому робот не разворачивается
    на переходе белое → чёрное.
    """
    if on_white_bg:
        # белый фон → линия чёрная: «темнее» = «ближе к линии»
        return right - left
    else:
        # чёрный фон → линия белая: «светлее» = «ближе к линии»
        return left - right


# ============================================================================
# 5. РЕЖИМ КАЛИБРОВКИ — узнай свои WHITE_REF и BLACK_REF
# ============================================================================

def mode_calib():
    print('Калибровка. За 5 секунд подноси робота к БЕЛОЙ и ЧЁРНОЙ клетке.')
    print('left = S1 (слева), right = S2 (справа)')
    t = StopWatch()
    while t.time() < 5000:
        print('left:', sensor_left.reflection(), ' right:', sensor_right.reflection())
        wait(100)
    print('Запиши значения в WHITE_REF и BLACK_REF вверху файла.')


# ============================================================================
# 6. ЗАЕЗД
# ============================================================================

def mode_run():
    print('Инверсная линия. Нажми любую кнопку на кирпиче — старт.')
    while not brick.buttons.pressed():
        wait(10)
    brick.speaker.beep(1000, 150)
    # Ждём отпускания кнопки, чтобы стартовое нажатие не засчиталось как «стоп»
    while brick.buttons.pressed():
        wait(10)
    wait(200)

    on_white_bg = True          # старт всегда на белой зоне (регламент 3.7)
    bg_level = float(WHITE_REF) # начальный фон — белый
    prev_error = 0.0
    line_seen = False           # уже ловили линию хоть раз?
    both_white_ms = 0           # сколько подряд мс оба датчика видят белое
    t = StopWatch()

    while t.time() < MAX_RUN_MS:
        left = sensor_left.reflection()
        right = sensor_right.reflection()

        # --- 1. На какой мы клетке? (плавная оценка средней яркости) ---
        avg = (left + right) / 2.0
        bg_level = bg_level + BG_ALPHA * (avg - bg_level)
        on_white_bg = cell_is_white(left, right, bg_level, on_white_bg)

        # --- 2. Ошибка и поворот (ПД-регулятор) ---
        error = line_error(left, right, on_white_bg)
        turn = KP * error + KD * (error - prev_error)
        turn = clamp(turn, -MAX_TURN, MAX_TURN)
        prev_error = error

        # --- 3. В крутых поворотах чуть сбавляем ход ---
        power = BASE_POWER - SLOW_DOWN * min(1.0, abs(error) / ERROR_FULL)

        # --- 4. Задаём мощность моторам напрямую ---
        motor_left.dc(clamp(power - turn, -100, 100))
        motor_right.dc(clamp(power + turn, -100, 100))

        # --- 5. Финиш: оба датчика видят белое в белой зоне ---
        if abs(error) > ON_LINE_ERROR:
            line_seen = True
        if line_seen and on_white_bg and left > BRIGHT_MARK and right > BRIGHT_MARK:
            both_white_ms += LOOP_MS
        else:
            both_white_ms = 0
        if both_white_ms >= FINISH_MS:
            break

        # --- 6. Любая кнопка посреди заезда — стоп (удобно на тренировке) ---
        if brick.buttons.pressed():
            print('Стоп по кнопке.')
            break

        wait(LOOP_MS)

    # --- Конец заезда: моторы в ноль ---
    motor_left.dc(0)
    motor_right.dc(0)
    brick.speaker.beep(880, 200)
    wait(100)
    brick.speaker.beep(1320, 300)
    print('Финиш. Время, мс:', t.time())


# ============================================================================
# 7. ПОДЪЁМ (мотор D, сзади) — задел на будущие полигоны, в этой программе
#    не вызывается. Пример использования смотри внизу.
# ============================================================================

def lift_up():
    """Поднять захват/тягу вверх (до упора, не дольше 2 секунд)."""
    lift_motor.dc(60)
    wait(2000)
    lift_motor.dc(0)


def lift_down():
    """Опустить захват/тягу вниз (до упора, не дольше 2 секунд)."""
    lift_motor.dc(-60)
    wait(2000)
    lift_motor.dc(0)


# ============================================================================
# 8. СТАРТ
# ============================================================================

if MODE == 'calib':
    mode_calib()
else:
    mode_run()

